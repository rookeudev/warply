export function localizeBackendMessage(message: string, t: Translator): string {
  const messages: Record<string, MessageKey> = {
    'Enter up to eight DNS IP addresses separated by commas.': 'invalidDns',
    'Enter an endpoint as hostname:port or [IPv6]:port.': 'invalidEndpoint',
    'Install Warply in Program Files before enabling Start with Windows.':
      'startupInstall',
    'Reconnect failed after five attempts. Select Connect to try again.':
      'reconnectFailed',
    'Could not reach Cloudflare. Check your internet connection and try again.':
      'networkError',
    'Cloudflare is rate limiting registrations. Please wait and try again.':
      'rateLimited',
    'Cloudflare returned an unexpected response. Its API may have changed.':
      'apiChanged',
    'WireGuard could not start the tunnel. Try again or reset the WARP account in Settings.':
      'tunnelError',
    'WireGuard could not stop the tunnel. Try again or check Windows Services.':
      'stopError',
    'This is not a supported WireGuard .conf file. Check that it has Interface and Peer sections with a private key, addresses, peer key, routes, and endpoint.':
      'invalidConfig',
    'This config contains a script or unsupported setting. Warply imports only standard tunnel fields.':
      'unsupportedConfig',
  }
  return messages[message] ? t(messages[message]) : message
}
